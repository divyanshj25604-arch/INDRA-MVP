function generateDeterministicEnsembles(
  baseLat: number,
  baseLng: number,
  count: number,
  direction: 'NW' | 'WNW' = 'NW'
) {
  const ensembles = [];
  const hours = [6, 12, 18, 24, 36, 48, 60, 72, 96, 120];

  for (let i = 1; i <= count; i++) {
    // Deterministic pseudo-random seed per member
    const seed = (i * 9301 + 49297) % 233280;
    const rnd = seed / 233280;
    const spreadAngle = (rnd - 0.5) * (direction === 'NW' ? 0.35 : 0.25);
    const speedVariation = 0.88 + rnd * 0.24;

    const points = [{ hour: 0, lat: baseLat, lng: baseLng, windKmh: 118 }];

    let curLat = baseLat;
    let curLng = baseLng;
    let curWind = 118;

    for (const h of hours) {
      const stepHours = h - points[points.length - 1].hour;
      const baseLatStep = (direction === 'NW' ? 0.08 : 0.04) * stepHours * speedVariation;
      const baseLngStep = (direction === 'NW' ? -0.055 : -0.11) * stepHours * speedVariation;

      // Add curvature and spread over time
      const latDrift = baseLatStep + spreadAngle * (h / 24) * 0.14;
      const lngDrift = baseLngStep + spreadAngle * (h / 24) * 0.12;

      curLat += latDrift;
      curLng += lngDrift;

      // Intensity curve: intensify before landfall, then decay
      if (h <= 24) {
        curWind += (18 - rnd * 10) * (stepHours / 12);
      } else {
        curWind -= (15 + rnd * 8) * (stepHours / 12);
      }
      curWind = Math.max(30, Math.min(175, Math.round(curWind)));

      points.push({
        hour: h,
        lat: Number(curLat.toFixed(2)),
        lng: Number(curLng.toFixed(2)),
        windKmh: curWind,
      });
    }

    ensembles.push({
      memberId: i,
      model: i % 2 === 0 ? ('WeatherNext-ENS' as const) : ('WeatherNext-PERT' as const),
      points,
    });
  }
  return ensembles;
}

